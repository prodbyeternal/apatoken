import Foundation

/// HDLC control types (HDLC_CONTROL).
enum HdlcControl: Equatable, CustomStringConvertible {
    case i
    case rr
    case rnr
    case snrm
    case disc
    case ua
    case dm
    case frmr
    case ui

    var description: String {
        switch self {
        case .i: return "I"
        case .rr: return "RR"
        case .rnr: return "RNR"
        case .snrm: return "SNRM"
        case .disc: return "DISC"
        case .ua: return "UA"
        case .dm: return "DM"
        case .frmr: return "FRMR"
        case .ui: return "UI"
        }
    }
}

/// HdlcNegotiationParameters
struct HdlcNegotiationParameters {
    var maxInfoFieldSizeToReceive: UInt16 = 0
    var maxInfoFieldSizeToTransmit: UInt16 = 0
    var windowSizeToReceive: UInt32 = 0
    var windowSizeToTransmit: UInt32 = 0
}

/// A pending frame generated by AddFramesToSend (HDLCFrameToSend).
struct HdlcFrameToSend {
    let control: HdlcControl
    let data: ByteBuffer
    let isLastSegment: Bool
}

/// Describes a frame to send (host side before encoding).
struct HdlcSendDescriptor {
    var sourceAddress: UInt32
    var destinationAddress: UInt32
    var control: HdlcControl
    var rSeq: Int
    var sSeq: Int
    var pf: Bool
    var lastSegment: Bool
    var data: ByteBuffer
}

/// Builds a single HDLC frame (HDLC.Prepare + ByteBuffer.AddAddress).
enum HdlcFrameBuilder {
    /// Mirrors HDLC.Prepare.
    static func prepare(_ send: HdlcSendDescriptor) throws -> [UInt8] {
        let buffer = ByteBuffer()
        var num = 0
        num += 1 // 2-byte length field (C# counts ++ first)
        num += 2
        num += addAddressBytes(buffer, send.destinationAddress, addAddressBytes: false, isDestinationAddress: true)
        num += addAddressBytes(buffer, send.sourceAddress, addAddressBytes: false, isDestinationAddress: false)
        num += 1 // control byte
        num += 2 // header checksum
        if send.data.count > 0 {
            num += send.data.count
            num += 2 // data checksum
        }
        num += 1 // footer frame boundary
        num -= 2 // frame boundaries

        buffer.add(126)
        let lengthHighBase: UInt8 = send.lastSegment ? 160 : 168 // 0xA0 / 0xA8
        buffer.add(lengthHighBase | UInt8((num >> 8) & 0xFF))
        buffer.add(UInt8(num & 0xFF))
        addAddressBytes(buffer, send.destinationAddress, addAddressBytes: true, isDestinationAddress: true)
        addAddressBytes(buffer, send.sourceAddress, addAddressBytes: true, isDestinationAddress: false)

        var controlByte: UInt8 = 0
        if send.pf { controlByte = 16 } // 0x10
        switch send.control {
        case .i:
            buffer.add(UInt8((0 | (send.sSeq << 1) | (send.rSeq << 5)) + Int(controlByte)))
        case .rr:
            buffer.add(1 | (UInt8(send.rSeq) << 5) | controlByte)
        case .rnr:
            buffer.add(5 | (UInt8(send.rSeq) << 5) | controlByte)
        case .snrm:
            buffer.add(0x83 | controlByte)
        case .disc:
            buffer.add(0x43 | controlByte)
        case .ua:
            buffer.add(0x0F | controlByte)
        case .dm:
            buffer.add(0x63 | controlByte)
        case .frmr:
            buffer.add(0x87 | controlByte)
        case .ui:
            buffer.add(3 | controlByte)
        }

        buffer.addHdlcChecksum()
        if send.data.count > 0 {
            buffer.addRange(send.data.toByteArray())
            buffer.addHdlcChecksum()
        }
        buffer.add(126)

        if buffer.count - 2 != num {
            throw TransportProtocolError(L.message.msgHDLCFrameCreatingError)
        }
        return buffer.toByteArray()
    }

    /// ByteBuffer.AddAddress(address, addAddressBytes, isDestinationAddress).
    @discardableResult
    static func addAddressBytes(_ buffer: ByteBuffer, _ address: UInt32, addAddressBytes add: Bool, isDestinationAddress: Bool) -> Int {
        var num = 0
        var value = address
        if isDestinationAddress {
            let logical = UInt16((address >> 16) & 0xFFFF)
            let physical = UInt16(address & 0xFFFF)
            var size = 1
            if logical >= 128 || physical >= 128 {
                size = 4
            } else if physical > 0 {
                size = 2
            }
            if !add {
                return size
            }
            value = UInt32(logical)
            var num6 = size / 2
            if num6 > 0 {
                num6 -= 1
            }
            repeat { // C# do-while: shift is read BEFORE the post-test decrement
                var b = UInt8(((value >> (7 * num6)) << 1) & 0xFF)
                num += 1
                if num == size {
                    b |= 1
                }
                buffer.add(b)
                let again = num6 > 0
                num6 -= 1
                if !again { break }
            } while true
            if size > 1 {
                value = UInt32(physical)
                num6 = size / 2
                while num6 > 0 { // C# while(num6-- > 0): decrement first, then shift
                    num6 -= 1
                    var b = UInt8(((value >> (7 * num6)) << 1) & 0xFF)
                    num += 1
                    if num == size {
                        b |= 1
                    }
                    buffer.add(b)
                }
            }
        } else {
            while value != 0 {
                var b = UInt8(((value << 1) & 0xFF))
                if value < 128 {
                    b |= 1
                }
                num += 1
                if add {
                    buffer.add(b)
                }
                value >>= 7
            }
        }
        return num
    }
}

/// One exchanged frame (FrameHDLC): builds the send frame and parses
/// the frame received in response.
final class ExchangedFrame {
    private(set) var sendDescriptor: HdlcSendDescriptor?
    private(set) var sendBytes: [UInt8] = []
    private(set) var sendControl: HdlcControl?
    private(set) var recvControl: HdlcControl = .ui
    private(set) var recvSSeq: Int = -1
    private(set) var recvRSeq: Int = -1
    private(set) var recvPF = false
    private(set) var recvLastSegment = true
    private(set) var recvData = ByteBuffer()
    private(set) var negotiatedParameters: HdlcNegotiationParameters?

    /// Mirrors FrameHDLC.SetSend.
    func setSend(_ desc: HdlcSendDescriptor) {
        sendDescriptor = desc
        sendControl = desc.control
        do {
            sendBytes = try HdlcFrameBuilder.prepare(desc)
        } catch {
            // Matches SetSend's swallow (result = 1); Prepare only
            // throws on the internal length mismatch, in which case the
            // subsequent Write would send nothing – surface it instead.
            sendBytes = []
        }
    }

    convenience init(sourceAddress: UInt32, destinationAddress: UInt32, control: HdlcControl, rSeq: Int, sSeq: Int, pf: Bool, lastSegment: Bool, data: ByteBuffer) {
        self.init()
        setSend(HdlcSendDescriptor(sourceAddress: sourceAddress,
                                   destinationAddress: destinationAddress,
                                   control: control,
                                   rSeq: rSeq,
                                   sSeq: sSeq,
                                   pf: pf,
                                   lastSegment: lastSegment,
                                   data: data))
    }

    /// Mirrors FrameHDLC.SetRecv – parses the received frame (HDLC.Set).
    func setRecv(_ raw: ByteBuffer) throws {
        if raw.count == 0 {
            throw TransportProtocolError(L.message.msgNoResponse)
        }
        if raw.count < 3 {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.fmt(L.message.msgWrongNumberOfBytes, "\(raw.count)", "3"))")
        }
        let frame = ByteBuffer(raw.toByteArray())
        if try frame.parseUInt8() != 126 {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.message.msgNoHeader)")
        }
        var num = try frame.parseUInt16()
        recvLastSegment = (num & 0x800) == 0
        if num >> 12 != 10 {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.message.msgInvalidFrame)")
        }
        num = num & 0x7FF
        if Int(num) + 2 != frame.count {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.fmt(L.message.msgWrongNumberOfBytes, "\(frame.count)", "\(Int(num) + 2)"))")
        }
        _ = try frame.parseAddress() // destination address (not compared)
        _ = try frame.parseAddress() // source address (not compared)
        let ctrl = try frame.parseUInt8()
        recvPF = (ctrl & 0x10) != 0
        if (ctrl & 1) == 0 {
            recvControl = .i
            recvSSeq = Int((ctrl >> 1) & 7)
            recvRSeq = Int((ctrl >> 5) & 7)
        } else if (ctrl & 0xF) == 1 {
            recvControl = .rr
            recvRSeq = Int((ctrl >> 5) & 7)
        } else if (ctrl & 0xF) == 5 {
            recvControl = .rnr
            recvRSeq = Int((ctrl >> 5) & 7)
        } else {
            switch ctrl & 0xEF {
            case 131: recvControl = .snrm
            case 67: recvControl = .disc
            case 99: recvControl = .ua
            case 15: recvControl = .dm
            case 135: recvControl = .frmr
            case 3: recvControl = .ui
            default: recvControl = .ui
            }
        }
        if try !frame.parseHdlcChecksum() {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.message.msgBadHeaderChecksum)")
        }
        let data = try frame.parseData(withLen8182: false, toEnd: 3, ignoreLengthValue: false)
        recvData = ByteBuffer(data.toByteArray())
        if recvData.count > 0 {
            if try !frame.parseHdlcChecksum() {
                throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.message.msgBadDataChecksum)")
            }
        }
        if try frame.parseUInt8() != 126 {
            throw TransportProtocolError("\(L.message.msgWrongResponseFromMeter) \(L.message.msgNoTile)")
        }
        if recvControl == .frmr {
            throw TransportProtocolError("FRMR - Frame Reject response")
        }
        guard recvControl == .ua, recvData.count > 0 else { return }
        let ua = ByteBuffer(recvData.toByteArray())
        if try ua.parseUInt8() != 129 {
            throw TransportProtocolError("No UA header first tag")
        }
        if try ua.parseUInt8() != 128 {
            throw TransportProtocolError("No UA header second tag")
        }
        let rest = try ua.parseData(withLen8182: true, toEnd: 0, ignoreLengthValue: false)
        let body = ByteBuffer(rest.toByteArray())
        var params = HdlcNegotiationParameters()
        while body.parseOffset < body.count {
            let tag = try body.parseUInt8()
            let value = try body.parseData(withLen8182: true, toEnd: 0, ignoreLengthValue: false)
            let v = ByteBuffer(value.toByteArray())
            switch tag {
            case 5:
                if value.count == 1 { params.maxInfoFieldSizeToReceive = UInt16(try v.parseUInt8()) }
                if value.count == 2 { params.maxInfoFieldSizeToReceive = try v.parseUInt16() }
            case 6:
                if value.count == 1 { params.maxInfoFieldSizeToTransmit = UInt16(try v.parseUInt8()) }
                if value.count == 2 { params.maxInfoFieldSizeToTransmit = try v.parseUInt16() }
            case 7:
                if value.count == 4 { params.windowSizeToReceive = try v.parseUInt32() }
            case 8:
                if value.count == 4 { params.windowSizeToTransmit = try v.parseUInt32() }
            default:
                break
            }
        }
        negotiatedParameters = params
    }

    /// FrameHDLC.IsLastSegmentReceived
    var isLastSegmentReceived: Bool { recvLastSegment }

    /// FrameHDLC.GetNextSSeq
    var nextSSeq: Int {
        guard let send = sendDescriptor, send.control == .i else { return 0 }
        return (send.sSeq + 1) % 8
    }

    /// FrameHDLC.GetNextRSeq
    var nextRSeq: Int {
        guard let send = sendDescriptor,
              send.control == .i || send.control == .rr else { return 0 }
        return (recvSSeq + 1) % 8
    }
}

/// TransportProtocolHdlc over a generic communication port.
final class HdlcTransport {
    private func hexDump(_ bytes: [UInt8], _ limit: Int) -> String {
        bytes.prefix(limit).map { String(format: "%02X", $0) }.joined()
    }
    private let port: CommunicationPort
    private let serverAddress: UInt32 // (logical << 16) | physical
    private let clientAddress: UInt32 = 41

    private var maxInfoFieldSizeToSend: UInt16 = 128
    private var maxInfoFieldSizeToReceive: UInt16 = 240
    private var negoMaxInfoFieldSizeToSend: UInt16 = 128

    private(set) var isHdlcConnected = false

    private var frames: [ExchangedFrame] = []
    private var framesToSend: [HdlcFrameToSend] = []
    private var rrrSequenceNext = 0
    private var sssSequenceNext = 0

    init(port: CommunicationPort, serverLogicalAddress: UInt16, serverPhysicalAddress: UInt16) {
        self.port = port
        serverAddress = (UInt32(serverLogicalAddress) << 16) | UInt32(serverPhysicalAddress)
    }

    func setFrameWindowSizes(_ toSend: UInt16, _ toReceive: UInt16) {
        maxInfoFieldSizeToReceive = toReceive
        maxInfoFieldSizeToSend = toSend
    }

    /// TransportProtocol.IsPortOpen() → underlying port open state.
    var isPortOpen: Bool {
        get async {
            await port.isOpen
        }
    }

    var negotiatedMaxInfoFieldSizeToSend: UInt16 {
        get { negoMaxInfoFieldSizeToSend }
        set { negoMaxInfoFieldSizeToSend = newValue }
    }

    // MARK: - Connect / disconnect

    /// Connect: Open, DISC (ignore outcomes), SNRM negotiation.
    func connect() async throws {
        framesToSend.removeAll()
        frames.removeAll()
        try await connectSpecific()
        try await doTransactionConnect()
    }

    private func connectSpecific() async throws {
        try await port.open()
        try await doTransactionDisconnect()
    }

    func disconnect(withTransactionDisconnect: Bool) async throws {
        var transportError: Error?
        var communicationError: Error?
        if withTransactionDisconnect {
            do {
                try await doTransactionDisconnect()
            } catch {
                transportError = error
            }
        }
        do {
            try await port.close()
        } catch {
            communicationError = error
        }
        if let transportError { throw transportError }
        if let communicationError { throw communicationError }
    }

    private func doTransactionDisconnect() async throws {
        framesToSend.removeAll()
        frames.removeAll()
        framesToSend.append(HdlcFrameToSend(control: .disc, data: ByteBuffer(), isLastSegment: true))
        try await doTransactionLoop()
        framesToSend.removeAll()
    }

    private func buildSnrmPayload() -> ByteBuffer {
        let payload = ByteBuffer()
        payload.add(129) // 0x81 format id
        payload.add(128) // 0x80 class
        payload.add(20)  // length 0x14 (2-byte length follows)
        payload.add(5)
        payload.add(2)
        payload.addUInt16(maxInfoFieldSizeToSend)
        payload.add(6)
        payload.add(2)
        payload.addUInt16(maxInfoFieldSizeToReceive)
        payload.add(7)
        payload.add(4)
        payload.addUInt32(1)
        payload.add(8)
        payload.add(4)
        payload.addUInt32(1)
        return payload
    }

    private func doTransactionConnect() async throws {
        framesToSend.removeAll()
        frames.removeAll()
        addFramesToSend(.snrm, buildSnrmPayload())
        let preCount = frames.count
        try await doTransactionLoop()
        framesToSend.removeAll()
        let negotiated = frames.count > preCount
            ? (frames[preCount].negotiatedParameters?.maxInfoFieldSizeToTransmit ?? 0)
            : 0
        negoMaxInfoFieldSizeToSend = negotiated
        if negoMaxInfoFieldSizeToSend == 0 {
            throw TransportProtocolError(L.message.msgHdlcSpaceForPayloadNotNegotiated)
        }
    }

    // MARK: - Transactions

    /// DoTransaction(dataToSend): wraps data with LLC, segments,
    /// exchanges all frames, concatenates the received data.
    func doTransaction(_ dataToSend: ByteBuffer) async throws -> ByteBuffer {
        let preCount = frames.count
        let wrapped = dataToSend.clone()
        // ByteBuffer.AddLLC: E6 E6 00 at buffer start.
        wrapped.insert(0, 230)
        wrapped.insert(1, 230)
        wrapped.insert(2, 0)
        addFramesToSend(.i, wrapped)
        try await doTransactionLoop()
        framesToSend.removeAll()
        let receivedCount = frames.count - preCount
        let queued = port.queuedBytes
        PortLog.shared.add("txn ▸ frames=\(receivedCount) windowFrom=\(preCount) queuedBytes=\(queued)")
        let received = ByteBuffer()
        var i = preCount
        while i < frames.count {
            received.addRange(frames[i].recvData.toByteArray())
            i += 1
        }
        let aggregate = received.toByteArray()
        PortLog.shared.add("agg ▸ \(aggregate.count)B \(hexDump(aggregate, 64))")
        try received.removeLLC()
        return received
    }

    private func addFramesToSend(_ frameType: HdlcControl, _ frameData: ByteBuffer) {
        if negoMaxInfoFieldSizeToSend == 0 {
            return
        }
        var offset = 0
        while true {
            let isLast = offset + Int(negoMaxInfoFieldSizeToSend) >= frameData.count
            framesToSend.append(HdlcFrameToSend(control: frameType,
                                                data: frameData.getRangeBuffer(offset, Int(negoMaxInfoFieldSizeToSend)),
                                                isLastSegment: isLast))
            if !isLast {
                offset += Int(negoMaxInfoFieldSizeToSend)
                continue
            }
            break
        }
    }

    /// DoTransaction(): send all frames; after each send, receive the
    /// answer; send RR continuations up to 100 times for segments.
    private func doTransactionLoop() async throws {
        guard !framesToSend.isEmpty else {
            throw TransportProtocolError(L.message.msgHdlcNoHdlcFramesToSend)
        }
        for frameToSend in framesToSend {
            let frame = ExchangedFrame()
            frames.append(frame)
            frame.setSend(HdlcSendDescriptor(sourceAddress: clientAddress,
                                             destinationAddress: serverAddress,
                                             control: frameToSend.control,
                                             rSeq: rrrSequenceNext,
                                             sSeq: frameToSend.control == .snrm ? 0 : sssSequenceNext,
                                             pf: true,
                                             lastSegment: frameToSend.isLastSegment,
                                             data: frameToSend.control == .snrm ? buildSnrmPayload() : frameToSend.data))
            try await port.write(frame.sendBytes)
            try frame.setRecv(try await receiveData())
            PortLog.shared.add("frame ▸ send=\(frame.sendControl?.description ?? "?") recv=\(frame.recvControl) pf=\(frame.recvPF) last=\(frame.isLastSegmentReceived) len=\(frame.recvData.count) data=\(hexDump(frame.recvData.toByteArray(), 48))")
            if frame.sendControl == .snrm && frame.recvControl == .ua {
                isHdlcConnected = true
            }
            if frame.sendControl == .disc && frame.recvControl == .ua {
                isHdlcConnected = false
            }
            if frame.sendControl == .disc && frame.recvControl == .dm {
                isHdlcConnected = false
            }
            sssSequenceNext = frame.nextSSeq
            rrrSequenceNext = frame.nextRSeq
            var lastSegmentReceived = frame.isLastSegmentReceived
            var continuations = 0
            while continuations < 100 {
                if lastSegmentReceived { break }
                let rrFrame = ExchangedFrame(sourceAddress: clientAddress,
                                             destinationAddress: serverAddress,
                                             control: .rr,
                                             rSeq: rrrSequenceNext,
                                             sSeq: sssSequenceNext,
                                             pf: true,
                                             lastSegment: true,
                                             data: ByteBuffer())
                try await port.write(rrFrame.sendBytes)
                try rrFrame.setRecv(try await receiveData())
                frames.append(rrFrame) // C# _frames.Add(frameHDLC2)
                PortLog.shared.add("frame ▸ send=RR recv=\(rrFrame.recvControl) pf=\(rrFrame.recvPF) last=\(rrFrame.isLastSegmentReceived) len=\(rrFrame.recvData.count) data=\(hexDump(rrFrame.recvData.toByteArray(), 48))")
                lastSegmentReceived = rrFrame.isLastSegmentReceived
                rrrSequenceNext = rrFrame.nextRSeq
                continuations += 1
            }
        }
        framesToSend.removeAll()
    }

    /// ReceiveData(): reads 3 bytes; if a valid HDLC start
    /// (`7E <len BE>`), reads the remaining `len-1` bytes.
    private func receiveData() async throws -> ByteBuffer {
        let part1 = ByteBuffer(try await port.read(3))
        if part1.count == 3 {
            let probe = ByteBuffer(part1.toByteArray())
            if try probe.parseUInt8() == 126 {
                let num = try probe.parseUInt16()
                let num2 = num & 0x7FF
                if num2 > 0 {
                    let result = ByteBuffer()
                    result.add(126)
                    result.addUInt16(num)
                    result.addRange(try await port.read(Int(num2) - 1))
                    let frameBytes = result.toByteArray()
                    PortLog.shared.add("recv ▸ \(frameBytes.count)B \(hexDump(frameBytes, 64))")
                    return result
                }
            }
        }
        let raw = part1.toByteArray()
        PortLog.shared.add("recv ▸ raw \(raw.count)B \(hexDump(raw, 32))")
        return part1
    }
}
